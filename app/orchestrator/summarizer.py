"""Ticket conversation summary with validation and a deterministic fallback
(docs/03 Section 8.9).

The summary is generated by a tool-free LLM call. Its output is
validated; any failure (provider error, empty, wrong shape, too long)
falls back to a deterministic summary built from the same trusted
inputs. The ticket is never blocked by a summary failure.
"""

from __future__ import annotations

import logging
from typing import Optional

from app.db.validation import TICKET_TEXT_MAX, validate_text
from app.llm.base import LLMClient, LLMError
from app.llm.tasks import SUMMARY_SYSTEM, build_summary_prompt

log = logging.getLogger("app.orchestrator")

HEADINGS = ("Customer Issue", "Relevant Context", "Actions Already Taken", "Current Status")
_ELLIPSIS = "…"


def _valid(text: object) -> Optional[str]:
    if not isinstance(text, str):
        return None
    cleaned = text.strip()
    if not cleaned.startswith(HEADINGS[0]):
        return None
    try:
        validate_text(cleaned, "conversation_summary", TICKET_TEXT_MAX)
    except (TypeError, ValueError):
        return None
    return cleaned


def fallback_summary(messages: list[str], facts: list[str], actions: list[str]) -> str:
    """Deterministic summary that always fits the 2,000 character limit."""
    def block(title: str, items: list[str]) -> str:
        return f"{title}\n" + "\n".join(items) if items else ""

    tail_parts = [block(HEADINGS[1], [f"- {f}" for f in facts[:5]]),
                  block(HEADINGS[2], [f"- {a}" for a in actions[:5]]),
                  f"{HEADINGS[3]}\nAwaiting support follow-up."]
    tail = "\n\n".join(p for p in tail_parts if p)
    head_budget = TICKET_TEXT_MAX - len(tail) - len(HEADINGS[0]) - 3
    if head_budget < 100:  # facts/actions too long: drop them, keep the status
        tail = f"{HEADINGS[3]}\nAwaiting support follow-up."
        head_budget = TICKET_TEXT_MAX - len(tail) - len(HEADINGS[0]) - 3
    body = "\n".join(messages)
    if len(body) > head_budget:
        body = body[: head_budget - 1] + _ELLIPSIS
    return f"{HEADINGS[0]}\n{body}\n\n{tail}"


def make_summary(llm: LLMClient, messages: list[str], facts: list[str], actions: list[str],
                 *, max_output_tokens: int = 512) -> tuple[str, str]:
    """Return ``(summary, source)`` where source is ``llm`` or ``fallback``."""
    try:
        raw = llm.complete(SUMMARY_SYSTEM, build_summary_prompt(messages, facts, actions),
                           max_output_tokens=max_output_tokens)
    except LLMError:
        log.warning("summary LLM call failed; using fallback")
        return fallback_summary(messages, facts, actions), "fallback"
    except Exception:  # a misbehaving adapter must not block the ticket
        log.warning("summary LLM call raised unexpectedly; using fallback")
        return fallback_summary(messages, facts, actions), "fallback"
    checked = _valid(raw)
    if checked is None:
        return fallback_summary(messages, facts, actions), "fallback"
    return checked, "llm"
